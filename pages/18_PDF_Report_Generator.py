import streamlit as st
from reportlab.lib.pagesizes import A4
from reportlab.pdfgen import canvas
from io import BytesIO
from datetime import datetime

st.title("📄 NEXUS AI PDF Report Generator")

city = st.selectbox(
    "🏙 Select City",
    [
        "Navsari",
        "Ahmedabad",
        "Mumbai",
        "Bombay"
    ]
)

flood_risk = st.slider(
    "🌊 Flood Risk (%)",
    0,
    100,
    40
)

aqi = st.slider(
    "🌫 AQI",
    0,
    500,
    95
)

temperature = st.slider(
    "🌡 Temperature (°C)",
    0,
    50,
    32
)

if st.button("📄 Generate PDF Report"):

    buffer = BytesIO()

    pdf = canvas.Canvas(
        buffer,
        pagesize=A4
    )

    width, height = A4

    pdf.setFont("Helvetica-Bold",20)
    pdf.drawString(
        50,
        800,
        "NEXUS AI Future Simulator"
    )

    pdf.setFont("Helvetica",14)
    pdf.drawString(
        50,
        770,
        "Smart City Risk Assessment Report"
    )

    pdf.line(
        50,
        760,
        550,
        760
    )

    pdf.setFont(
        "Helvetica",
        12
    )

    pdf.drawString(
        50,
        720,
        f"City : {city}"
    )

    pdf.drawString(
        50,
        690,
        f"Flood Risk : {flood_risk}%"
    )

    pdf.drawString(
        50,
        660,
        f"Air Quality Index : {aqi}"
    )

    pdf.drawString(
        50,
        630,
        f"Temperature : {temperature} °C"
    )

    pdf.drawString(
        50,
        600,
        f"Date : {datetime.now().strftime('%d-%m-%Y')}"
    )

    pdf.line(
        50,
        570,
        550,
        570
    )

    pdf.setFont(
        "Helvetica-Bold",
        14
    )

    pdf.drawString(
        50,
        530,
        "AI Analysis"
    )

    pdf.setFont(
        "Helvetica",
        12
    )

    if flood_risk >= 70:
        status = "HIGH RISK"
        recommendation = (
            "Expand Water Reservoirs, "
            "Deploy Emergency Teams, "
            "Activate Flood Warning System."
        )
    elif flood_risk >= 40:
        status = "MEDIUM RISK"
        recommendation = (
            "Monitor Water Levels and "
            "Improve Drainage Infrastructure."
        )
    else:
        status = "LOW RISK"
        recommendation = (
            "Current Conditions Stable."
        )

    pdf.drawString(
        50,
        490,
        f"Risk Status : {status}"
    )

    pdf.drawString(
        50,
        450,
        "Recommendations:"
    )

    text = pdf.beginText(
        50,
        420
    )

    text.textLines(
        recommendation
    )

    pdf.drawText(text)

    pdf.line(
        50,
        150,
        550,
        150
    )

    pdf.drawString(
        50,
        120,
        "Generated by NEXUS Smart City AI Platform"
    )

    pdf.save()

    pdf_data = buffer.getvalue()

    st.success(
        "✅ PDF Report Generated Successfully"
    )

    st.download_button(
        label="⬇ Download PDF Report",
        data=pdf_data,
        file_name=f"{city}_NEXUS_Report.pdf",
        mime="application/pdf"
    )
